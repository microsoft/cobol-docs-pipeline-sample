CREATE SCHEMA DEMODATA;

CREATE TABLE DEMODATA.ORDERS (
    ORDER_ID CHAR(10) NOT NULL PRIMARY KEY,
    CUSTOMER_ID CHAR(10) NOT NULL,
    ORDER_STATUS VARCHAR(10) NOT NULL,
    ORDER_TOTAL DECIMAL(11, 2) NOT NULL,
    UPDATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE DEMODATA.ORDAUD (
    ORDER_ID CHAR(10) NOT NULL,
    ACTION_CODE CHAR(10) NOT NULL,
    RESULT_CODE CHAR(10) NOT NULL,
    EVENT_TIMESTAMP CHAR(26) NOT NULL
);

